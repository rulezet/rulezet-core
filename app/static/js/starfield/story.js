const pick = (pair) => (pair ? (getLang() === 'fr' ? pair[1] : pair[0]) : '');

/** { name, brief, radio: [2], outro } of a level, in the current language, or null */
export function levelStory(world, index) {
    const s = S[`${world}-${index}`];
    if (!s) return null;
    return { name: pick(s[0]), brief: pick(s[1]), radio: [pick(s[2]), pick(s[3])].filter(Boolean), outro: pick(s[4]) };
}

export function actText(key) {
    const a = ACT[key];
    return a ? { title: pick(a[0]), text: pick(a[1]) } : null;
}

