"""
rule_deep_analysis_agent.py — RuleDeepAnalysisAgent(AIAgent)

The second Rule Analysis script, "In-depth report": a long, contextual
report on ONE rule, instead of the standard script's compact structured
breakdown (rule_analysis_agent.py, which stays the default). Picked at
launch time on the rule's AI Analysis page / the AI admin; both scripts
store their reports as agent_key='rule_analysis' AIGeneration rows, told
apart by meta['script'].

Grounded on app/features/rule/rule_ai_core.py's material: rule content and
metadata, full ATT&CK entries, CVE details from Vulnerability Lookup
(CVSS, EPSS, CWE, affected products, SSVC), quality-score failures, linked
rules and bundles.

The rule itself is the core of the report: threat background on whatever
malware / actor / campaign / tool it names, every metadata field, then an
element-by-element walkthrough of the whole content — one call per slice
of the rule (up to MAX_SLICES), so a long rule is covered in full — and a
deep read of its condition. CVE / ATT&CK sections only appear when the
rule has them.

Written section by section like bundle_analysis_agent.py (a single "write
3000 words as JSON" call never finishes on CPU-only Ollama). Unlike the
bundle report, previous sections are NOT replayed in full into the next
call — only a short digest — so ~15-20 long sections plus the rule
material still fit the shared 8k context window. The system prompt + material
prefix stays byte-identical across calls, so Ollama's prompt cache reads
the rule only once.
"""
import json

from app.features.ai.ai_core import (
    AgentInvalidResponse,
    AgentResult,
    AIAgent,
    UNTRUSTED_DATA_PREAMBLE,
    strip_control_chars,
)

SCRIPT_KEY = 'deep'

_SEVERITIES  = {'critical', 'high', 'medium', 'low', 'info'}
_CONFIDENCES = {'high', 'medium', 'low'}

# (title, brief, word target, condition). condition: None = always,
